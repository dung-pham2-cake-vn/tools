#!/usr/bin/env node
// Bakes every spec under ./specs into specs/specs-index.js so index.html can
// browse them with no server (file:// works — fetch() does not).
// Run: node open_api_viewer/build-specs-index.mjs
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(fileURLToPath(import.meta.url));
const SPECS = join(ROOT, 'specs');
const OUT = join(SPECS, 'specs-index.js');
const KEEP = /\.(ya?ml)$/i;

async function walk(dir) {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    if (e.name.startsWith('.')) continue;
    const abs = join(dir, e.name);
    if (e.isDirectory()) out.push(...await walk(abs));
    else if (KEEP.test(e.name)) out.push(abs);
  }
  return out;
}

const files = (await walk(SPECS)).sort();
const entries = [];
const data = {};
for (const abs of files) {
  const rel = relative(SPECS, abs).split(/[\\/]/).join('/');
  const text = await readFile(abs, 'utf8');
  entries.push({ path: rel, size: Buffer.byteLength(text) });
  data[rel] = text;
}

const js = `// GENERATED by build-specs-index.mjs — do not edit.
window.SPECS_INDEX = ${JSON.stringify({ count: entries.length, files: entries }, null, 2)};
window.SPECS_DATA = ${JSON.stringify(data)};
`;
await writeFile(OUT, js);
console.log(`specs-index.js: ${entries.length} specs, ${(Buffer.byteLength(js) / 1024).toFixed(0)} KB`);
